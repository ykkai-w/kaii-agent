import assert from "node:assert/strict";
import fs from "node:fs";
import test from "node:test";

const root = new URL("../../", import.meta.url);
const publicFiles = ["README.md", "CONTRIBUTING.md", "SECURITY.md", "docs/ARCHITECTURE.md", "docs/AGENT-HARNESS.md"];

test("公开说明使用正面、具体的表述，作者保持用户身份", () => {
  for (const file of publicFiles) {
    const text = fs.readFileSync(new URL(file, root), "utf8");
    assert.doesNotMatch(text, /不是|不代表|并非|不意味着|真正的.{0,12}而是|说白了|赋能|降维|闭环|底座|抓手|—|–/, file);
    assert.doesNotMatch(text, /(?:作者|author)\s*[:：]?\s*\[?(?:codex|claude|openai)\b|co-authored-by|generated by/i, file);
    assert.doesNotMatch(text, /\/Users\/|HANDOVER-|PROGRESS\.md/, file);
  }
  const readme = fs.readFileSync(new URL("README.md", root), "utf8");
  assert.match(readme, /^# kaii-agent\n/);
  assert.equal(readme.match(/^## .+/m)?.[0], "## 完整功能与操作清单");
  assert.ok(readme.indexOf("| T14 |") < readme.indexOf("## 部分功能示例"));
  assert.doesNotMatch(readme, /\]\(#完整功能与操作清单\)|<details>/i);
  assert.doesNotMatch(readme, /(?<!!)\[[^\]]*\]\(docs\/images\//);
  assert.match(readme, /作者 \[ykkai-w\]/);
  for (const provider of ["DeepSeek", "GLM", "Kimi"]) assert.ok(readme.includes(provider));
});

test("README 的本机图片和文档链接可读取", () => {
  const readme = fs.readFileSync(new URL("README.md", root), "utf8");
  const links = [...readme.matchAll(/\]\(([^)]+)\)/g)].map((match) => match[1]);
  for (const link of links.filter((link) => !/^https?:|^#/.test(link))) {
    assert.ok(fs.statSync(new URL(link, root)).size > 0, link);
  }
});

test("README 中文段落和标题紧跟英文，表格逐项双语", () => {
  const readme = fs.readFileSync(new URL("README.md", root), "utf8");
  const withoutCode = readme.replace(/```[^\n]*\n[\s\S]*?```/g, "");
  const paragraphs = withoutCode.split(/\n\s*\n/).map((part) => part.trim()).filter(Boolean);
  const visibleText = (text) => text.replace(/\]\([^)]+\)/g, "]");
  const chinese = /[\u3400-\u9fff]/;
  for (let index = 0; index < paragraphs.length; index += 1) {
    const paragraph = paragraphs[index];
    if (paragraph.startsWith("|")) {
      for (const row of paragraph.split("\n")) {
        for (const cell of row.split("|").slice(1, -1)) {
          if (!chinese.test(cell)) continue;
          const [original, translation] = cell.split("<br>");
          assert.ok(chinese.test(original), cell);
          assert.ok(translation && /[a-z]/i.test(translation), cell);
          assert.doesNotMatch(visibleText(translation), chinese, cell);
        }
      }
      continue;
    }
    if (paragraph.startsWith("![") || !chinese.test(visibleText(paragraph))) continue;
    const translation = paragraphs[index + 1];
    assert.ok(translation && /[a-z]/i.test(translation), paragraph);
    assert.doesNotMatch(visibleText(translation), chinese, paragraph);
    assert.ok(!translation.startsWith("|"), paragraph);
  }
});

test("README 功能清单编号唯一，界面语言切换保持规划状态", () => {
  const readme = fs.readFileSync(new URL("README.md", root), "utf8");
  const ids = [...readme.matchAll(/^\| ([A-Z]\d{2}) \|/gm)].map((match) => match[1]);
  assert.equal(ids.length, 301);
  assert.equal(new Set(ids).size, ids.length);
  assert.equal(new Set(ids.map((id) => id[0])).size, 14);
  assert.match(readme, /参考 Claude Code、Codex/);
  assert.match(readme, /当前界面使用中文。下一步计划加入/);
  assert.match(readme, /待真机验证/);
  assert.equal([...readme.matchAll(/!\[[^\]]*\]\(docs\/images\/native-[^)]+\)/g)].length, 13);
});
